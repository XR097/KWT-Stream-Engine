#!/usr/bin/env python3
"""Generate the project copies of the E203 (hbirdv2) SoC files used by the KSE SoC.

Every change is an exact text substitution on the pinned upstream file and must
match exactly once, so the patch stays minimal and reviewable:

  sirv_plic_top      -> kse_sirv_plic_top      : source 17 (io_devices_0_16), PLIC_IRQ_NUM 18
  e203_subsys_plic   -> kse_e203_subsys_plic   : kse_irq input -> source 17
  e203_subsys_mems   -> kse_e203_subsys_mems   : O5 narrowed to 1 MiB decode at 0x4000_0000 and
                                                 exported as the shared SRAM CPU port
                                                 (example AXI bridge/slave removed)
  e203_subsys_main   -> kse_e203_subsys_main   : kse_accel_sys (shared SRAM + engine) on hfclk /
                                                 bus_rst_n; PPI O12 (SysPer) goes to the engine
                                                 MMIO, the legacy sysper port is tied off;
                                                 loader port + kse_clk/kse_rst_n exported
  e203_subsys_top    -> kse_e203_subsys_top    : pass the loader port through
  e203_soc_top       -> kse_e203_soc_top       : pass the loader port through
  apb_uart           -> apb_uart (same name)   : fifo_tx_data default (no inferred TX data latch)

Instance names are unchanged so upstream hierarchical paths keep working.
Usage: make_e203_copies.py [--check]   (--check: fail if the committed copies differ)
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UP = ROOT / "third-party/e203/rtl/e203"
OUT = ROOT / "rtl/kse_soc"
HDR = "// Generated by tools/kse_soc/make_e203_copies.py from upstream {src} (sha256 {sha}).\n" \
      "// Do not edit by hand; change the generator instead.\n"


def sub(s, old, new, count=1):
    n = s.count(old)
    if n != count:
        raise SystemExit(f"patch anchor found {n} times (expected {count}):\n{old}")
    return s.replace(old, new)


# loader port bundle: (direction at the SoC boundary, width, name)
LDR = [("input", "", "cmd_valid"), ("output", "", "cmd_ready"), ("input", "[31:0]", "cmd_addr"),
       ("input", "", "cmd_read"), ("input", "[31:0]", "cmd_wdata"), ("input", "[3:0]", "cmd_wmask"),
       ("output", "", "rsp_valid"), ("input", "", "rsp_ready"), ("output", "[31:0]", "rsp_rdata"),
       ("output", "", "rsp_err")]
CLK = [("output", "", "kse_clk"), ("output", "", "kse_rst_n")]


def port_decls(term_last):
    lines = ["  // KSE parameter loader (shared SRAM master 1) (ICB only)"]
    items = [(d, w, "kse_ldr_" + n) for d, w, n in LDR] + CLK
    for i, (d, w, n) in enumerate(items):
        sep = "" if (term_last and i == len(items) - 1) else ","
        lines.append(f"  {d:<6} {w:<7} {n}{sep}")
    return "\n".join(lines) + "\n"


def port_conns(term_last):
    items = ["kse_ldr_" + n for _, _, n in LDR] + [n for _, _, n in CLK]
    lines = []
    for i, n in enumerate(items):
        sep = "" if (term_last and i == len(items) - 1) else ","
        lines.append(f"    .{n:<24}({n}){sep}")
    return "\n".join(lines) + "\n"


def plic_top(s):
    s = sub(s, "module sirv_plic_top(", "module kse_sirv_plic_top(")
    s = sub(s, "  input   io_devices_0_15,\n", "  input   io_devices_0_15,\n  input   io_devices_0_16,\n")
    s = sub(s, "localparam PLIC_IRQ_NUM = 17;", "localparam PLIC_IRQ_NUM = 18;")
    s = sub(s, "                  io_devices_0_15  ,\n", "                  io_devices_0_16  ,\n                  io_devices_0_15  ,\n")
    return s


def subsys_plic(s):
    s = sub(s, "module e203_subsys_plic(", "module kse_e203_subsys_plic(")
    s = sub(s, "  input  wdg_irq_a,\n", "  input  kse_irq,   // KSE engine, PLIC source 17\n  input  wdg_irq_a,\n")
    s = sub(s, "  sirv_plic_top u_sirv_plic_top(", "  kse_sirv_plic_top u_sirv_plic_top(")
    s = sub(s, "    .io_devices_0_15 (plic_irq_i_15),\n", "    .io_devices_0_15 (plic_irq_i_15),\n    .io_devices_0_16 (kse_irq),\n")
    return s


SHRAM = [("output", "", "cmd_valid"), ("input", "", "cmd_ready"), ("output", "[31:0]", "cmd_addr"),
         ("output", "", "cmd_read"), ("output", "[31:0]", "cmd_wdata"), ("output", "[3:0]", "cmd_wmask"),
         ("input", "", "rsp_valid"), ("output", "", "rsp_ready"), ("input", "[31:0]", "rsp_rdata"),
         ("input", "", "rsp_err")]


def subsys_mems(s):
    s = sub(s, "module e203_subsys_mems(\n",
            "module kse_e203_subsys_mems(\n  // O5: shared SRAM CPU port (1 MiB decode at 0x4000_0000)\n" +
            "".join(f"  {d:<6} {w:<7} kse_shram_icb_{n},\n" for d, w, n in SHRAM))
    s = sub(s, "  .O5_BASE_REGION_LSB (28),", "  .O5_BASE_REGION_LSB (20),")
    begin = s.index("      // * Here is an example AXI Peripheral\n  wire expl_axi_arvalid;")
    end = s.index("  );\n", s.index("sirv_expl_axi_slv # (")) + len("  );\n")
    glue = "  // O5 -> shared SRAM CPU port (replaces the upstream example AXI bridge and slave)\n"
    for d, _, n in SHRAM:
        if d == "output":
            glue += f"  assign kse_shram_icb_{n} = expl_axi_icb_{n};\n"
        else:
            glue += f"  assign expl_axi_icb_{n} = kse_shram_icb_{n};\n"
    s = s[:begin] + glue + s[end:]
    return s


def subsys_main(s):
    s = sub(s, "module e203_subsys_main(", "module kse_e203_subsys_main(")
    s = sub(s, "  input  test_mode,\n\n  input  ls_clk,\n", port_decls(False) + "\n  input  test_mode,\n\n  input  ls_clk,\n")
    icb = [("", "cmd_valid"), ("", "cmd_ready"), ("[31:0]", "cmd_addr"), ("", "cmd_read"),
           ("[31:0]", "cmd_wdata"), ("[3:0]", "cmd_wmask"), ("", "rsp_valid"), ("", "rsp_ready"),
           ("[31:0]", "rsp_rdata"), ("", "rsp_err")]
    decl = "  // KSE accelerator subsystem nets\n"
    decl += "".join(f"  wire {w:<7} kse_mmio_icb_{n};\n" for w, n in icb)
    decl += "".join(f"  wire {w:<7} kse_shram_icb_{n};\n" for w, n in icb)
    decl += "  wire         kse_irq;\n\n"
    s = sub(s, " e203_subsys_plic u_e203_subsys_plic(", decl + " kse_e203_subsys_plic u_e203_subsys_plic(")
    s = sub(s, "    .plic_ext_irq           (plic_ext_irq),\n",
            "    .plic_ext_irq           (plic_ext_irq),\n    .kse_irq                (kse_irq),\n")
    # PPI O12 (SysPer) -> engine MMIO
    s = sub(s, "(sysper_icb_", "(kse_mmio_icb_", count=10)
    s = sub(s, "e203_subsys_mems u_e203_subsys_mems(\n",
            "kse_e203_subsys_mems u_e203_subsys_mems(\n" +
            "".join(f"    .kse_shram_icb_{n:<10}(kse_shram_icb_{n}),\n" for _, _, n in SHRAM))
    add = "\n  // ---------------- KSE accelerator subsystem ----------------\n"
    add += "  // legacy SysPer port: O12 now belongs to the engine\n"
    add += ("  assign sysper_icb_cmd_valid = 1'b0;\n  assign sysper_icb_cmd_addr  = {`E203_ADDR_SIZE{1'b0}};\n"
            "  assign sysper_icb_cmd_read  = 1'b0;\n  assign sysper_icb_cmd_wdata = {`E203_XLEN{1'b0}};\n"
            "  assign sysper_icb_cmd_wmask = {`E203_XLEN/8{1'b0}};\n  assign sysper_icb_rsp_ready = 1'b1;\n")
    add += "  assign kse_clk   = hfclk;\n  assign kse_rst_n = bus_rst_n;\n\n"
    add += "  kse_accel_sys u_kse_sys (\n    .clk(hfclk), .rst_n(bus_rst_n),\n"
    for _, n in icb:
        add += f"    .cpu_{n:<10}(kse_shram_icb_{n}),\n"
    for _, n in icb:
        add += f"    .mmio_{n:<10}(kse_mmio_icb_{n}),\n"
    for _, _, n in LDR:
        add += f"    .ldr_{n:<16}(kse_ldr_{n}),\n"
    add += "    .irq(kse_irq)\n  );\n\n"
    i = s.rindex("endmodule")
    s = s[:i] + add + s[i:]
    return s


def subsys_top(s):
    s = sub(s, "module e203_subsys_top(", "module kse_e203_subsys_top(")
    s = sub(s, "  input  test_iso_override,\n  input  test_mode \n  );",
            port_decls(False) + "  input  test_iso_override,\n  input  test_mode \n  );")
    s = sub(s, "  e203_subsys_main  u_e203_subsys_main(", "  kse_e203_subsys_main  u_e203_subsys_main(")
    s = sub(s, "    .test_mode     (test_mode), \n    .ls_clk        (lfextclk), ",
            port_conns(False) + "    .test_mode     (test_mode), \n    .ls_clk        (lfextclk), ")
    return s


def soc_top(s):
    s = sub(s, "module e203_soc_top(", "module kse_e203_soc_top(")
    s = sub(s, "  output io_pads_aon_pmu_padrst_o_oval,\n  output io_pads_aon_pmu_vddpaden_o_oval \n);",
            "  output io_pads_aon_pmu_padrst_o_oval,\n  output io_pads_aon_pmu_vddpaden_o_oval,\n\n" +
            port_decls(True) + ");")
    s = sub(s, " e203_subsys_top u_e203_subsys_top(", " kse_e203_subsys_top u_e203_subsys_top(")
    s = sub(s, "    .io_pads_dbgmode2_n_i_ival       (io_pads_dbgmode2_n_i_ival) \n",
            "    .io_pads_dbgmode2_n_i_ival       (io_pads_dbgmode2_n_i_ival),\n" + port_conns(True))
    return s


def apb_uart(s):
    # UART TX FIFO fix: the TX FIFO
    # samples data_i only when valid_i && ready_o, so the idle value of fifo_tx_data
    # is unobservable; a default removes the 8-bit inferred data latch per UART.
    # The module name stays apb_uart (the upstream file is excluded from file lists).
    return sub(s, "        fifo_tx_valid   = 1'b0;        \n",
               "        fifo_tx_valid   = 1'b0;        \n"
               "        fifo_tx_data    = 8'b0;  // project fix: no inferred data latch\n")


JOBS = [("perips/sirv_plic_top.v", "kse_sirv_plic_top.v", plic_top),
        ("subsys/e203_subsys_plic.v", "kse_e203_subsys_plic.v", subsys_plic),
        ("subsys/e203_subsys_mems.v", "kse_e203_subsys_mems.v", subsys_mems),
        ("subsys/e203_subsys_main.v", "kse_e203_subsys_main.v", subsys_main),
        ("subsys/e203_subsys_top.v", "kse_e203_subsys_top.v", subsys_top),
        ("soc/e203_soc_top.v", "kse_e203_soc_top.v", soc_top),
        ("perips/apb_uart/apb_uart.v", "apb_uart.v", apb_uart)]


def main():
    # Closed port set: generation fails if any non-ICB loader signal returns.
    expected = {"cmd_valid", "cmd_ready", "cmd_addr", "cmd_read", "cmd_wdata", "cmd_wmask",
                "rsp_valid", "rsp_ready", "rsp_rdata", "rsp_err"}
    assert {n for _, _, n in LDR} == expected
    accel = (OUT / "kse_accel_sys.sv").read_text().split(");", 1)[0]
    assert set(re.findall(r"\bldr_(\w+)", accel)) == expected, "non-ICB loader SoC port"
    check = "--check" in sys.argv
    bad = 0
    for src, dst, fn in JOBS:
        raw = (UP / src).read_bytes()
        text = HDR.format(src=src, sha=hashlib.sha256(raw).hexdigest()) + fn(raw.decode())
        p = OUT / dst
        if check:
            if not p.exists() or p.read_text() != text:
                print("DIFFERS", p); bad += 1
        else:
            p.write_text(text)
            print("wrote", p.relative_to(ROOT), hashlib.sha256(raw).hexdigest()[:16])
    if check:
        print("E203_COPIES_OK" if not bad else "E203_COPIES_STALE")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
