#!/usr/bin/env python3
"""Generate the KSE hardwired ROMs (SystemVerilog case tables) from the frozen profile.

Outputs (default rtl/kse/):
  kse_exp_rom.sv   Softmax exp table, 257 x u16 (compact Q15, model independent)
  kse_gelu_rom.sv  GELU middle tables, selected by layer number (12 layers;
                   identical tables are shared)

The window [minimum_input, maximum_input] of each GELU table travels in the
layer header of the parameter stream (pack_params.py checks that it matches
the ROM size).
"""
import argparse
import json
from pathlib import Path

import numpy as np


def npy(pdir, key):
    return np.load(Path(pdir) / (key.replace(".", "__") + ".npy"))


def gen_exp(pdir):
    t = npy(pdir, "softmax.exp_q15_compact").astype(np.int64)
    if t.size != 257 or t.min() < 0 or t.max() > 0xFFFF:
        raise ValueError("unexpected exp table")
    lines = ["// Generated by tools/kse/gen_roms.py from the frozen profile. Do not edit.",
             "// Softmax exp table softmax.exp_q15_compact (257 x u16).",
             "module kse_exp_rom (input logic [8:0] addr, output logic [15:0] data);",
             "  always_comb begin", "    case (addr)"]
    for i, v in enumerate(t):
        lines.append(f"      9'd{i}: data = 16'd{int(v)};")
    lines += ["      default: data = 16'd0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(lines)


def gen_gelu(pdir, profile):
    keys, sel = [], []
    for b in profile["blocks"]:
        k = profile["gelu_configs"][f"{b}.gelu"]["table_key"]
        if k not in keys:
            keys.append(k)
        sel.append(keys.index(k))
    tabs = [npy(pdir, k).astype(np.int64) for k in keys]
    for k, t in zip(keys, tabs):
        if t.min() < -128 or t.max() > 127 or t.size > 256:
            raise ValueError(f"bad GELU table {k}")
    sw = max(1, (len(keys) - 1).bit_length())
    lines = ["// Generated by tools/kse/gen_roms.py from the frozen profile. Do not edit.",
             "// GELU middle tables, one per layer: " + ", ".join(f"b{i:02d}->{keys[s]}" for i, s in enumerate(sel)),
             "module kse_gelu_rom (input logic [3:0] layer, input logic [7:0] addr, output logic signed [7:0] data);",
             f"  logic [{sw - 1}:0] tsel;",
             "  always_comb begin", "    case (layer)"]
    for i, s in enumerate(sel):
        lines.append(f"      4'd{i}: tsel = {sw}'d{s};")
    lines += ["      default: tsel = '0;", "    endcase", "  end",
              "  always_comb begin", "    data = 8'sd0;", "    case (tsel)"]
    for s, (k, t) in enumerate(zip(keys, tabs)):
        lines.append(f"      {sw}'d{s}: case (addr)  // {k}, {t.size} entries")
        for i, v in enumerate(t):
            lines.append(f"        8'd{i}: data = {'-' if v < 0 else ''}8'sd{abs(int(v))};")
        lines.append("        default: data = 8'sd0;")
        lines.append("      endcase")
    lines += ["      default: data = 8'sd0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", required=True)
    ap.add_argument("--output-dir", default=str(Path(__file__).resolve().parents[2] / "rtl" / "kse"))
    a = ap.parse_args()
    p = json.loads((Path(a.profile) / "profile.json").read_text())
    out = Path(a.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    wrap = lambda t: "`default_nettype none\n" + t + "`default_nettype wire\n"
    (out / "kse_exp_rom.sv").write_text(wrap(gen_exp(a.profile)))
    (out / "kse_gelu_rom.sv").write_text(wrap(gen_gelu(a.profile, p)))
    print("ROM_GENERATED kse_exp_rom.sv kse_gelu_rom.sv")


if __name__ == "__main__":
    main()
